# ============================================================
# サイドバー用：コンパクトな折りたたみ表示
# ============================================================
def render_help_section():
    with st.expander("📖 統計用語の説明", expanded=False):
        search = st.text_input("用語を検索", placeholder="例：p値、要因...", key="glossary_search_sidebar")
        filtered = {
            k: v for k, v in GLOSSARY.items()
            if not search or any(
                search.lower() in s.lower()
                for s in [k, v["short"], v["detail"]]
            )
        }
        if not filtered:
            st.info("該当する用語が見つかりませんでした。")
            return
        for term, content in filtered.items():
            with st.expander(f"**{term}** — {content['short']}", expanded=False):
                st.markdown(content["detail"])
                if content.get("example"):
                    st.code(content["example"], language=None)

